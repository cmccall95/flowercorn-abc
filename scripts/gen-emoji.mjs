// Bundles Microsoft Fluent Emoji (flat, MIT) SVGs for every emoji used in src/, so art looks the same on
// every device and works offline. Run automatically before dev/build; writes src/content/emojiArt.gen.ts.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const require = createRequire(import.meta.url);
const icons = require('@iconify-json/fluent-emoji-flat/icons.json');
const chars = require('@iconify-json/fluent-emoji-flat/chars.json');

const files = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) return files(p);
    return /\.(ts|tsx)$/.test(f) && !f.endsWith('.gen.ts') && !f.includes('.test.') ? [p] : [];
  });

const used = new Set();
for (const f of files('src')) {
  for (const m of readFileSync(f, 'utf8').matchAll(/\p{Extended_Pictographic}(️)?/gu)) used.add(m[0]);
}

const code = (e) => [...e].map((c) => c.codePointAt(0).toString(16)).filter((h) => h !== 'fe0f').join('-');
const resolve = (name) => icons.icons[name] ?? (icons.aliases?.[name] && icons.icons[icons.aliases[name].parent]);

const out = {};
const missing = [];
for (const e of [...used].sort()) {
  const name = chars[code(e)] ?? chars[code(e) + '-fe0f'];
  const icon = name && resolve(name);
  if (!icon) { missing.push(e); continue; }
  const w = icon.width ?? icons.width ?? 32;
  const h = icon.height ?? icons.height ?? 32;
  out[e.replace('️', '')] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}">${icon.body}</svg>`;
}

writeFileSync(
  'src/content/emojiArt.gen.ts',
  `// Generated by scripts/gen-emoji.mjs from @iconify-json/fluent-emoji-flat (Microsoft Fluent Emoji, MIT). Do not edit.\n` +
    `export const EMOJI_ART: Record<string, string> = ${JSON.stringify(out, null, 0)};\n`,
);
console.log(`emoji art: ${Object.keys(out).length} bundled${missing.length ? `, using system emoji for ${missing.join(' ')}` : ''}`);
